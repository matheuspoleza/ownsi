export function diagnosticsCatalogue(): string {
  const sections = DIAGNOSIS_CODES.map((code) => section(SAMPLES[code]))
  return `${PREAMBLE}\n${sections.join("\n")}`
}

function section(diagnosis: Diagnosis): string {
  const payload = toDiagnosisResponse(diagnosis, CHALLENGE)

  return [
    `## ${payload.code}`,
    "",
    payload.cause,
    "",
    `**What to do.** ${payload.fix}`,
    "",
    "```json",
    JSON.stringify(payload, null, 2),
    "```",
    "",
  ].join("\n")
}

